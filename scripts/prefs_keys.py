#!/usr/bin/env python3
"""prefs_keys.py - every rc.ini key the rebuild reads, with its type and built-in default.

Scans dlls/ for the PREFS_* lookups (heading and key as string literals or #define'd names)
and the curses' CBaseCurse::GetPrefsFloat, whose key is the curse name plus a suffix. With
--ini, adds the value RC 1.9's shipped rc.ini gives each key and lists the shipped keys
nothing reads. When recovered/decomp/ exists (the Ghidra export, see DECOMPILE.md), also
checks that every literal heading/key the original looks up is one ours looks up, and exits 1
if not: a missing one means a function RC changed still has the stock body, or a key is
misspelled.

Writes docs/RC_INI.md.
Usage: scripts/prefs_keys.py [--ini path/to/rc.ini] [--check]
  --check  exit 1 if docs/RC_INI.md is not what this run would write
"""
import argparse, collections, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DLLS = os.path.join(ROOT, "dlls")
DECOMP = os.path.join(ROOT, "recovered", "decomp")
ORIG_CALL = re.compile(r"\bPREFS_\w+\(\s*\"([^\"]+)\"\s*,\s*\"([^\"]+)\"")
OUT = os.path.join(ROOT, "docs", "RC_INI.md")

TYPES = {
    "PREFS_KeyLoopUpString": "string",
    "PREFS_KeyLoopUpInt": "int",
    "PREFS_KeyLoopUpFloat": "float",
    "PREFS_KeyLoopUpBool": "bool",
    "PREFS_KeyLoopUpIntClamp": "int",
    "PREFS_KeyLoopUpFloatClamp": "float",
    "PREFS_LookUpWithDefualtCreate": "string",
}
CALL = re.compile(r"\b(" + "|".join(TYPES) + r")\(\s*(\"[^\"]*\"|\w+)\s*,\s*\"([^\"]+)\"\s*,\s*")
CURSE = re.compile(r"\bGetPrefsFloat\(\s*\"([^\"]+)\"\s*,\s*")
CURSE_NAME = re.compile(r"InherGetCurseName\(\)\s*\{\s*return\s+\"([^\"]+)\"")
DEFINE = re.compile(r"#define\s+(\w+)\s+\"([^\"]+)\"")


def arg_text(src, i):
    """The call argument starting at src[i], up to the next top-level ',' or ')'."""
    depth, j = 0, i
    while j < len(src):
        c = src[j]
        if c in "([":
            depth += 1
        elif c in ")]":
            if depth == 0:
                break
            depth -= 1
        elif c == "," and depth == 0:
            break
        elif c == '"':
            j = src.index('"', j + 1)
        j += 1
    return " ".join(src[i:j].split())


def norm_default(t, d):
    if t == "string":
        return d.strip('"')
    m = re.fullmatch(r"(-?[0-9.]+)f?", d)
    if m and t == "float":
        return "%g" % float(m.group(1))
    return d


def scan():
    sources = {}
    for name in sorted(os.listdir(DLLS)):
        if name.endswith((".cpp", ".h")) and not name.startswith("Preff."):
            sources[name] = open(os.path.join(DLLS, name), encoding="latin-1").read()
    defines = {}
    for src in sources.values():
        defines.update(dict(DEFINE.findall(src)))

    keys = collections.OrderedDict()  # (heading, key) -> {type, defaults, files}
    unresolved = []

    def add(head, key, t, default, fname):
        e = keys.setdefault((head, key), {"type": t, "defaults": [], "files": []})
        if default not in e["defaults"]:
            e["defaults"].append(default)
        if fname not in e["files"]:
            e["files"].append(fname)

    curse_names = []
    for fname, src in sources.items():
        curse_names += CURSE_NAME.findall(src)
        for m in CALL.finditer(src):
            func, head, key = m.groups()
            if head.startswith('"'):
                head = head.strip('"')
            elif head in defines:
                head = defines[head]
            else:
                unresolved.append("%s: %s(%s, ...)" % (fname, func, head))
                continue
            add(head, key, TYPES[func], norm_default(TYPES[func], arg_text(src, m.end())), fname)
        for m in CURSE.finditer(src):
            add("CURSES", "<curse>" + m.group(1), "float", norm_default("float", arg_text(src, m.end())), fname)
    curse_names = [n for n in curse_names if n != "Base"]
    return keys, unresolved, curse_names


def read_ini(path):
    ini, head = collections.OrderedDict(), None
    for line in open(path, encoding="latin-1"):
        line = line.rstrip("\r\n")
        if line.startswith("[") and line.endswith("]"):
            head = line[1:-1]
        elif "=" in line and head:
            k, v = line.split("=", 1)
            ini[(head, k)] = v
    return ini


def shipped_value(ini, head, key, curse_names):
    if key.startswith("<curse>"):
        vals = sorted({ini[(head, n + key[7:])] for n in curse_names if (head, n + key[7:]) in ini})
        return ", ".join(vals) if vals else None
    return ini.get((head, key))


def render(keys, unresolved, curse_names, ini):
    out = []
    w = out.append
    w("# rc.ini keys")
    w("")
    w("Generated by `scripts/prefs_keys.py`; don't edit by hand. Every key the rebuild reads from")
    w("`rc.ini` (the file `sv_prefsfile` names, in the game directory), with the default the code")
    w("uses when the key is missing. A missing key is added to the in-memory table with that default,")
    w("and `saveprefs` writes it out (docs/SERVER.md).")
    w("")
    w("Curse keys are per curse: `<curse>` is one of %s." % ", ".join("`%s`" % n for n in curse_names))
    if ini is not None:
        w("The `shipped` column is RC 1.9's own `rc.ini`; a blank one means the release doesn't set it.")
    w("")
    by_head = collections.OrderedDict()
    for (head, key), e in sorted(keys.items()):
        by_head.setdefault(head, []).append((key, e))
    for head, rows in by_head.items():
        w("## [%s]" % head)
        w("")
        cols = ["key", "type", "default"] + (["shipped"] if ini is not None else []) + ["read in"]
        body = []
        for key, e in rows:
            r = [key, e["type"], " / ".join(e["defaults"])]
            if ini is not None:
                v = shipped_value(ini, head, key, curse_names)
                r.append("" if v is None else v)
            r.append(" ".join(e["files"]))
            body.append(r)
        widths = [max(len(c), *(len(r[i]) for r in body)) for i, c in enumerate(cols)]
        w("```")
        w("  ".join(c.ljust(widths[i]) for i, c in enumerate(cols)).rstrip())
        for r in body:
            w("  ".join(v.ljust(widths[i]) for i, v in enumerate(r)).rstrip())
        w("```")
        w("")
    if ini is not None:
        read = set(keys)
        curse_suffixes = [k[7:] for (h, k) in keys if h == "CURSES" and k.startswith("<curse>")]
        unread = []
        for (head, key) in ini:
            if (head, key) in read:
                continue
            if head == "CURSES" and any(key == n + s for n in curse_names for s in curse_suffixes):
                continue
            unread.append("[%s] %s" % (head, key))
        w("## Shipped keys nothing reads")
        w("")
        if unread:
            w("```")
            out.extend(unread)
            w("```")
        else:
            w("None.")
        w("")
    if unresolved:
        w("## Lookups with a computed heading")
        w("")
        w("```")
        out.extend(unresolved)
        w("```")
        w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ini")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    keys, unresolved, curse_names = scan()
    ini = read_ini(a.ini) if a.ini else None
    text = render(keys, unresolved, curse_names, ini)
    missing = []
    if os.path.isdir(DECOMP):
        orig = set()
        for name in os.listdir(DECOMP):
            orig.update(ORIG_CALL.findall(open(os.path.join(DECOMP, name), encoding="latin-1").read()))
        missing = sorted(orig - set(keys))
        for head, key in missing:
            print("original reads [%s] %s, ours doesn't" % (head, key))
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("docs/RC_INI.md is stale: run scripts/prefs_keys.py" + (" --ini " + a.ini if a.ini else ""))
            sys.exit(1)
        sys.exit(1 if missing else 0)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("%d keys in %d headings -> %s" % (len(keys), len({h for h, _ in keys}), os.path.relpath(OUT, ROOT)))
    if missing:
        sys.exit(1)


if __name__ == "__main__":
    main()
